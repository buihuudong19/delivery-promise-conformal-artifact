def _extra_macros(cfg, t, add):
    """Numbers quoted in the text that are not contrasts: sensitivity of RQ1, periods, RDD, checks, region promises,
    Olist by year, calibration weights. Names: pd + parts in CamelCase, digits spelled out."""
    ap = lambda a: "Alpha" + ALPHA.get(round(float(a), 2), "X")
    vk = lambda v: v.replace("_ipcw", " ipcw").replace("_plain", " plain")
    if (t / "sensitivity_rq1.csv").is_file():
        for _, r in pd.read_csv(t / "sensitivity_rq1.csv").iterrows():
            k = SENS_KEY.get(r["setting"])
            if k is None:
                continue
            per = "Test" if str(r["period"]).startswith("2018") else ""
            base = ("Sens", k, per, vk(r["variant"]), ap(r["alpha"]))
            add(_name(*base, "Cov"), _fmt(r["coverage"], 1, True))
            add(_name(*base, "Cov All"), _fmt(r["coverage_all"], 1, True))
            add(_name(*base, "Len"), _fmt(r["mean_promise"], 1))
            add(_name(*base, "Worst"), _fmt(r["worst_region"], 1, True))
            add(_name(*base, "Min"), _fmt(r["coverage_min_window"], 1, True))
            if pd.notna(r.get("share_capped", np.nan)):
                add(_name(*base, "Cap"), _fmt(r["share_capped"], 1, True))
    if (t / "rq1_summary_by_period.csv").is_file():
        B = pd.read_csv(t / "rq1_summary_by_period.csv")
        keep = B["variant"].isin([cfg["rq3"]["model"], "xgbq_ipcw", (cfg.get("ensemble") or {}).get("name", "")])
        for _, r in B[keep & B["group"].isin(GROUP_KEY)].iterrows():
            base = ("Per", GROUP_KEY[r["group"]], vk(r["variant"]), r["method"], ap(r["alpha"]))
            add(_name(*base, "Cov"), _fmt(r["coverage"], 1, True)); add(_name(*base, "Min"), _fmt(r["coverage_min"], 1, True))
            add(_name(*base, "Len"), _fmt(r["mean_promise"], 1))
            if pd.notna(r.get("worst_region", np.nan)):
                add(_name(*base, "Worst"), _fmt(r["worst_region"], 1, True))
    W = pd.read_csv(t / "rq1_window_metrics.csv")
    o = W[(W.variant == "olist") & (W.region == "all")].copy(); o["y"] = pd.to_datetime(o["origin"]).dt.year
    for y, g in o.groupby("y"):
        add(_name("Olist", "Year", str(y), "Cov"), _fmt(g["coverage"].mean(), 1, True))
        add(_name("Olist", "Year", str(y), "Len"), _fmt(g["mean_promise"].mean(), 1))
    add(_name("Olist", "Eval", "Cov"), _fmt(o["coverage"].mean(), 1, True))
    add(_name("Olist", "Eval", "Cov All"), _fmt(o["coverage_all"].mean(), 1, True))
    add(_name("Olist", "Eval", "Late"), _fmt(1 - o["coverage"].mean(), 1, True))
    add(_name("Olist", "Eval", "Len"), _fmt(o["mean_promise"].mean(), 1))
    oreg = W[(W.variant == "olist") & (W.region != "all")].groupby("k")["coverage"].min().mean()
    add(_name("Olist", "Eval", "Worst"), _fmt(oreg, 1, True))
    Wt = pd.read_csv(t / "rq1_window_types.csv")
    add(_name("N", "Stress", "Windows"), str(int(Wt["stress"].sum())))
    add(_name("Stress", "Threshold"), _fmt(Wt["threshold"].iloc[0], 1, True))
    add(_name("N", "Test", "Windows"), str(int(Wt["period"].str.startswith("2018").sum())))
    if (t / "rq1_calibration_weights.csv").is_file():
        Cw = pd.read_csv(t / "rq1_calibration_weights.csv")
        add(_name("Cal", "N", "Mean"), f"{Cw['n_cal'].mean():,.0f}"); add(_name("Cal", "Neff", "Mean"), f"{Cw['n_eff'].mean():,.0f}")
        add(_name("Cal", "Obs", "Share"), _fmt((Cw["n_obs"] / Cw["n_cal"]).mean(), 1, True))
    Cb = pd.read_csv(t / "rq1_censoring_by_origin.csv")
    add(_name("Tail", "Share", "Mean"), _fmt(Cb["tail_share"].mean(), 2, True))
    # RQ2: RDD at S = 0 with the rule-of-thumb M, and regional risk differences for >= 4 days late
    R = pd.read_csv(t / "rq2_rdd.csv")
    R = R[(R.cutoff == 0) & np.isclose(R["M"], R["M_rule_of_thumb"])]
    for _, r in R.iterrows():
        sub = "All" if r["subset"] == "all" else "After"
        nm = _name("Rdd", sub, "H", str(int(r["h"])))
        add(nm, f"{100 * r['estimate']:.1f}"); add(nm + "Ci", f"[{100 * r['ci_lo']:.1f}, {100 * r['ci_hi']:.1f}]")
        add(nm + "Half", f"{50 * (r['ci_hi'] - r['ci_lo']):.1f}")
    Pl = pd.read_csv(t / "rq2_rdd.csv"); Pl = Pl[(Pl.cutoff != 0) & np.isclose(Pl["M"], Pl["M_rule_of_thumb"])]
    if len(Pl):
        add(_name("Rdd", "Placebo", "Cover"), _fmt(((Pl.ci_lo <= 0) & (Pl.ci_hi >= 0)).mean(), 0, True))
        add(_name("Rdd", "Placebo", "N"), str(len(Pl)))
    Rg = pd.read_csv(t / "rq2_aipw_bins_by_region.csv")
    late4 = Rg[(Rg.learner == "lr") & (Rg["bin"] >= 4)]
    add(_name("Region", "Rd", "Late", "Min"), _fmt(late4["rd"].min(), 0, True))
    add(_name("Region", "Rd", "Late", "Max"), _fmt(late4["rd"].max(), 0, True))
    # RQ3: region promises at the matched length, checks of the optimisation
    Rp = pd.read_csv(t / "rq3_region_promises.csv").groupby(["region", "policy"])[["mean_promise", "late_realised"]].mean()
    for (reg, pol), r in Rp.iterrows():
        add(_name("Region", "Promise", reg, pol), _fmt(r["mean_promise"], 1))
        add(_name("Region", "Late", reg, pol), _fmt(r["late_realised"], 1, True))
    G = pd.read_csv(t / "rq3_duality_gap.csv")
    add(_name("Duality", "Gap", "Max"), f"{100 * G['gap'].max():.4f}"); add(_name("Duality", "Cases"), str(len(G)))
    Cv = pd.read_csv(t / "rq3_convexity.csv")
    add(_name("Convex", "All"), _fmt(Cv["share_convex"].mean(), 0, True))
    add(_name("Convex", "Mid"), _fmt(Cv["share_convex_P15_40"].mean(), 0, True))
    Cc = pd.read_csv(t / "rq3_curve_calibration.csv"); oos = Cc[Cc["out_of_sample"]]
    add(_name("Curve", "Oos", "Bias"), f"{100 * (oos['predicted_fit2017'] - oos['observed']).mean():+.2f}")
    add(_name("Curve", "Oos", "Corr"), f"{np.corrcoef(oos['predicted_fit2017'], oos['observed'])[0, 1]:.2f}")
    Q = pd.read_csv(t / "rq3_matched.csv"); d = Q["optimal_low_realised_at_L"] - Q["low_olist"]
    st = Q["k"].isin(Wt.loc[Wt["stress"], "k"])
    add(_name("Rq", "Three", "Win", "Share"), _fmt((d < 0).mean(), 0, True))
    add(_name("Rq", "Three", "Gain", "Stress"), f"{100 * d[st].mean():.2f}"); add(_name("Rq", "Three", "Gain", "Normal"), f"{100 * d[~st].mean():.2f}")
    if "optimal_share_at_max_P" in Q:
        add(_name("Rq", "Three", "At", "Max"), _fmt(Q["optimal_share_at_max_P"].mean(), 1, True))
        add(_name("Olist", "Above", "Max"), _fmt(Q["olist_share_above_max_P"].mean(), 2, True))
    # checks (recomputed from the tables they summarise)
    Tc = pd.read_csv(t / "rq1_tuning_choices.csv"); Tc = Tc[Tc["tuned_here"]]
    add(_name("Tuning", "Edge", "Share"), _fmt(Tc[["xgbq_edge", "qrf_edge", "aft_scale_edge"]].mean().mean(), 0, True))
    Th = pd.read_csv(t / "theory_checks.csv")
    add(_name("Checks", "Rows"), str(len(Th))); add(_name("Checks", "N"), str(Th["check"].nunique()))
    for st_ in ("PASS", "INFO", "FAIL"):
        add(_name("Checks", st_.lower()), str(int((Th["status"] == st_).sum())))
    import re
    c4 = Th[Th["claim"].str.contains("share of origins", regex=False)]
    if len(c4):
        own = dict(re.findall(r"(\w[\w-]*) ([0-9.]+)", c4["value"].iloc[0].split("|")[0]))
        wor = dict(re.findall(r"(\w[\w-]*) ([0-9.]+)", c4["value"].iloc[0].split("|")[1]))
        add(_name("Mondrian", "Own", "North"), _fmt(float(own.get("Norte", "nan")), 0, True))
        add(_name("Mondrian", "Worst", "North"), _fmt(float(wor.get("Norte", "nan")), 0, True))
    c6 = Th[(Th["check"] == "C6") & Th["claim"].str.contains("alpha = 0.1 ")]
    if len(c6):
        nums = re.findall(r"[0-9.]+", c6["value"].iloc[0])
        add(_name("Aci", "Miscov", "Ten"), nums[0]); add(_name("Aci", "Gap", "Ten"), nums[1]); add(_name("Aci", "Bound", "Ten"), nums[2])
    c5 = Th[(Th["check"] == "C5") & Th["claim"].str.contains("alpha = 0.1:")]
    if len(c5):
        add(_name("Oracle", "Below", "Ten"), re.findall(r"windows below nominal - 2 pp: (\d+)", c5["value"].iloc[0])[0])
