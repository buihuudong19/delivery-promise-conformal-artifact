"""LaTeX macros with every number quoted in the text (outputs/manuscript/results_macros.tex).

The text of the article uses only these macros, so that a re-run updates every number.
Macro names contain letters only; digits are spelled out (alpha 0.10 -> AlphaTen).
"""
import numpy as np
import pandas as pd

WORD = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five", "6": "Six", "7": "Seven",
        "8": "Eight", "9": "Nine"}
ALPHA = {0.05: "Five", 0.10: "Ten", 0.20: "Twenty"}


def _name(*parts):
    words = " ".join(str(p).replace("_", " ") for p in parts).split()
    s = "".join(w[:1].upper() + w[1:] for w in words)
    s = "".join(WORD.get(ch, ch) for ch in s)
    return "pd" + "".join(ch for ch in s if ch.isalpha())


def _measure(family):
    """Measure of a contrast family: Worst (worst-region coverage, pp), Len (days) or Cov (coverage, pp). The family
    'promise length at Olist's coverage (days)' is a length, although its name contains 'coverage'."""
    f = family.lower()
    if "worst-region" in f:
        return "Worst"
    if "(days)" in f or "promise" in f or "length" in f:
        return "Len"
    return "Cov"


def _fmt(x, nd=1, pct=False):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "n/a"
    return f"{x * 100:.{nd}f}" if pct else f"{x:.{nd}f}"


def write_macros(cfg, out):
    t = out / "tables"
    L = ["% Generated by the P2DU pipeline (stage macros). Do not edit by hand."]

    def add(name, val):
        L.append(f"\\newcommand{{\\{name}}}{{{val}}}")

    fl = pd.read_csv(t / "sample_flow.csv")
    for i, r in fl.iterrows():
        add(_name("Flow", "Step", WORD[str(i)]), f"{int(r['n_orders']):,}")
    P = pd.read_csv(t / "eda_promise_checks.csv").set_index("check")["value"]
    add(_name("Olist", "Late", "Rate"), _fmt(P["late rate (S > 0) among delivered orders"], 1, True))
    add(_name("Olist", "Mean", "Promise"), _fmt(P["promise P in days: mean"], 1))
    add(_name("Olist", "Median", "Slack"), _fmt(P["median slack P - D among on-time orders (days)"], 0))
    S = pd.read_csv(t / "rq1_summary.csv")
    for _, r in S[S.region == "all"].iterrows():
        a = "Olist" if pd.isna(r["alpha"]) else "Alpha" + ALPHA.get(round(r["alpha"], 2), "X")
        add(_name("Cov", r["variant"], r["method"], a), _fmt(r["coverage"], 1, True))
        add(_name("Len", r["variant"], r["method"], a), _fmt(r["mean_promise"], 1))
        if pd.notna(r.get("worst_region")):
            add(_name("Worst", r["variant"], r["method"], a), _fmt(r["worst_region"], 1, True))
    if (t / "contrasts_rq1.csv").is_file():
        C = pd.read_csv(t / "contrasts_rq1.csv")
        for _, r in C.iterrows():
            fam = r["family"].split(" ")[0]
            kind = _measure(r["family"])
            nm = _name("Ctr", fam, r["contrast"].replace(":", " ").replace("-", " minus "),
                       r["family"].split("alpha=")[-1] if "alpha=" in r["family"] else "",
                       "Test" if "2018 test" in r["family"] else "", kind)
            sc = 1 if kind == "Len" else 100
            add(nm, f"{r['mean'] * sc:.2f} [{r['ci_lo'] * sc:.2f}, {r['ci_hi'] * sc:.2f}]")
    A = pd.read_csv(t / "rq2_aipw_bins.csv")
    for _, r in A.iterrows():
        b = WORD[str(int(r["bin"]))]
        add(_name("Aipw", r["learner"], "Risk", b), _fmt(r["risk"], 1, True))
        add(_name("Aipw", r["learner"], "RR", b), f"{r['rr']:.2f} [{r['rr_lo']:.2f}, {r['rr_hi']:.2f}]")
        if pd.notna(r["e_value"]):
            add(_name("Aipw", r["learner"], "Evalue", b), f"{r['e_value']:.2f}")
    V = pd.read_csv(t / "rq2_s_versus_d.csv").set_index("model")
    for m in V.index:
        add(_name("Cvll", m.replace("(", " ").replace(")", " ").replace("+", " plus ")), f"{V.loc[m, 'cv_logloss']:.4f}")
    Mm = pd.read_csv(t / "rq2_survey_mechanism.csv")
    late = Mm[Mm.late == 1].set_index("answered_before_delivery")
    add(_name("Late", "Answered", "Before", "Share"), _fmt(late.loc[1, "share_within_late_group"], 1, True))
    add(_name("Late", "Low", "Before"), _fmt(late.loc[1, "mean"], 1, True))
    add(_name("Late", "Low", "After"), _fmt(late.loc[0, "mean"], 1, True))
    if (t / "rq3_matched.csv").is_file():
        Q = pd.read_csv(t / "rq3_matched.csv")
        add(_name("Rq", "Three", "Olist", "Low"), _fmt(Q["low_olist"].mean(), 2, True))
        add(_name("Rq", "Three", "Olist", "Len"), _fmt(Q["L_olist"].mean(), 1))
        for fam in ("uniform", "route", "cpd_quantile", "late_optimal", "optimal", "olist_shift"):
            add(_name("Rq", "Three", fam, "Low", "At", "L"), _fmt(Q[f"{fam}_low_realised_at_L"].mean(), 2, True))
            add(_name("Rq", "Three", fam, "Len", "At", "Low"), _fmt(Q[f"{fam}_L_at_low"].mean(), 1))
    if (t / "contrasts_rq3.csv").is_file():
        C = pd.read_csv(t / "contrasts_rq3.csv")
        C = C[C.family.str.startswith("RQ3 ")]       # main families; RQ3-Y and RQ3-R are in tools/gen_results_tex.py
        for _, r in C.iterrows():
            sc = 1 if "length" in r["family"] else 100
            add(_name("Ctr", "Rq", "Three", r["family"].split(" ")[1], r["contrast"].replace("-", " minus ")),
                f"{r['mean'] * sc:.2f} [{r['ci_lo'] * sc:.2f}, {r['ci_hi'] * sc:.2f}]")
    if (t / "rq2_lee_bounds.csv").is_file():
        Lb = pd.read_csv(t / "rq2_lee_bounds.csv")
        for i, r in Lb.iterrows():
            tag = "Cell" if i == 0 else "Two Cells"
            add(_name("Lee", tag, "Bounds"), f"[{100 * r['bound_lo']:.1f}, {100 * r['bound_hi']:.1f}]")
            add(_name("Lee", tag, "Ci"), f"[{100 * r['ci_lo']:.1f}, {100 * r['ci_hi']:.1f}]")
            add(_name("Lee", tag, "Trim"), _fmt(r["trim_share"], 1, True))
    if (t / "contrasts_rq3_sensitivity.csv").is_file():
        C = pd.read_csv(t / "contrasts_rq3_sensitivity.csv")
        fam_key = {"low-rating rate at Olist's mean promise (all windows)": "Low",
                   "low-rating rate at Olist's mean promise (2018 test)": "Low Test",
                   "late rate at Olist's mean promise (all windows)": "Late",
                   "promise length at Olist's low-rating rate (all windows)": "Len",
                   "quantile-average versus forest CPD (low-rating rate at Olist's mean promise)": "Ens Vs Forest Low",
                   "quantile-average versus forest CPD (late rate at Olist's mean promise)": "Ens Vs Forest Late"}
        set_key = {"forest CPD (main)": "Main", "quantile-average CPD": "Ens", "policy from the 2017 curve": "Fit 2017",
                   "three-star ratings as not low": "Neutral", "optimal": "Optimal", "coverage policy": "Coverage",
                   "tail mass at 42 days": "Tail 42", "tail mass at 56 days": "Tail 56", "tail mass at 70 days": "Tail 70",
                   "tail mass at 120 days": "Tail 120"}
        for _, r in C[C.family.str.startswith("RQ3-S ")].iterrows():     # RQ3-X: tools/gen_results_tex.py
            fk = fam_key[r["family"].replace("RQ3-S ", "", 1)]
            ck = set_key[r["contrast"].split(": ")[-1]] if r["contrast"].startswith("optimal - Olist") else \
                set_key[r["contrast"].split(":")[0]]
            sc = 1 if fk == "Len" else 100
            add(_name("Ctr", "Rq", "Three", "Sens", fk, ck), f"{r['mean'] * sc:.2f} [{r['ci_lo'] * sc:.2f}, {r['ci_hi'] * sc:.2f}]")
            add(_name("Holm", "Rq", "Three", "Sens", fk, ck), "<0.001" if r["p_holm"] < 0.001 else f"{r['p_holm']:.3f}")
    _extra_macros(cfg, t, add)
    seen, uniq = {}, []
    for line in L:
        key = line.split("}")[0]
        if key in seen:
            if seen[key] != line:      # two different numbers under one name: a naming error, never drop silently
                raise ValueError(f"macro name collision: {seen[key]} / {line}")
            continue
        seen[key] = line; uniq.append(line)
    m = out / "manuscript"; m.mkdir(parents=True, exist_ok=True)
    (m / "results_macros.tex").write_text("\n".join(uniq) + "\n", encoding="utf-8")


